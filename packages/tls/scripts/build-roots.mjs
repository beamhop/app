// Generates src/generated/mozilla-roots.ts from the Mozilla CA list as redistributed by the curl
// project (https://curl.se/docs/caextract.html). Data licence: MPL-2.0.
//
//   node scripts/build-roots.mjs                 # download https://curl.se/ca/cacert.pem
//   node scripts/build-roots.mjs path/to/cacert.pem
//
// Each certificate is reduced to its trust-anchor fields (subject, SPKI, name constraints) by
// webpki itself (wasm `pack_anchor`), so no ASN.1 is parsed in JavaScript. Run build:wasm first.
import { createHash, X509Certificate } from 'node:crypto'
import { readFileSync, writeFileSync } from 'node:fs'
import { fileURLToPath } from 'node:url'
import init, { pack_anchor } from '../src/generated/beamhop_tls_wasm.js'

const SOURCE = 'https://curl.se/ca/cacert.pem'
const gen = fileURLToPath(new URL('../src/generated/', import.meta.url))
const arg = process.argv[2]
let pemBytes
if (arg) pemBytes = readFileSync(arg)
else {
  const res = await fetch(SOURCE)
  if (!res.ok) throw new Error(`${SOURCE}: HTTP ${res.status}`)
  pemBytes = Buffer.from(await res.arrayBuffer())
}
const pem = pemBytes.toString('latin1')
const sha256 = createHash('sha256').update(pemBytes).digest('hex')
const date = /Certificate data from Mozilla (?:as of|last updated on): (.+)/.exec(pem)?.[1]?.trim()
if (!date) throw new Error('unexpected cacert.pem header: no date line')

await init({ module_or_path: readFileSync(gen + 'beamhop_tls_wasm_bg.wasm') })

const parts = []
const keyTypes = {}
const skipped = []
let count = 0
for (const m of pem.matchAll(/-----BEGIN CERTIFICATE-----[\s\S]+?-----END CERTIFICATE-----/g)) {
  const x = new X509Certificate(m[0])
  try {
    parts.push(pack_anchor(x.raw))
  } catch (e) {
    skipped.push(`${x.subject.replace(/\n/g, ', ')}: ${e.message}`)
    continue
  }
  count++
  const k = x.publicKey
  const d = k.asymmetricKeyDetails ?? {}
  const label = k.asymmetricKeyType === 'rsa' ? `rsa-${d.modulusLength}` : k.asymmetricKeyType === 'ec' ? `ec-${d.namedCurve}` : k.asymmetricKeyType
  keyTypes[label] = (keyTypes[label] ?? 0) + 1
}
if (count < 100) throw new Error(`only ${count} roots parsed; refusing to write a suspiciously small store`)
const packed = Buffer.concat(parts)
const info = { source: SOURCE, date, sha256, count }

const lines = packed.toString('base64').match(/.{1,120}/g)
writeFileSync(
  gen + 'mozilla-roots.ts',
  `// GENERATED by scripts/build-roots.mjs. Do not edit.
// Trust anchors (subject, SPKI, name constraints) of the Mozilla CA list, from ${SOURCE}
// Upstream bundle date: ${date}; sha256 ${sha256}; ${count} roots.
// This data is subject to the Mozilla Public License, v. 2.0 (https://mozilla.org/MPL/2.0/).
import type { RootStoreInfo } from '../roots'

export const MOZILLA_ROOTS_INFO: RootStoreInfo = ${JSON.stringify(info)}

/** Packed: per root \`u16be len | subject\`, \`u16be len | spki\`, \`u16be len | nameConstraints\`; base64. */
export const MOZILLA_ROOTS_PACKED_B64 =
${lines.map((l) => `  '${l}'`).join(' +\n')}
`,
)
writeFileSync(gen + 'mozilla-roots.json', JSON.stringify({ ...info, generated: new Date().toISOString().slice(0, 10), packedBytes: packed.length, keyTypes, skipped }, null, 2) + '\n')
console.log({ ...info, packedBytes: packed.length, keyTypes, skipped })
