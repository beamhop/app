import { test, expect, devices, type Page } from '@playwright/test'
const RELAY = 'ws://localhost:7777'
const OUT = process.env.SHOTS_DIR || 'test-results/shots'
const open = (p: Page, hash = '') => p.goto(`/?relay=${encodeURIComponent(RELAY)}#/${hash}`)

test('screens', async ({ browser }) => {
  const mk = async (mobile: boolean) => (await browser.newContext(mobile ? { ...devices['iPhone 13'], deviceScaleFactor: 1 } : { viewport: { width: 1280, height: 820 } })).newPage()
  const alice = await mk(false)
  const bob = await mk(true)
  await open(alice)
  await alice.screenshot({ path: `${OUT}/01-landing-desktop.png` })
  await open(bob)
  await bob.screenshot({ path: `${OUT}/02-landing-mobile.png` })
  await alice.getByRole('button', { name: 'Hop a Room' }).click()
  await alice.getByPlaceholder('Your name').fill('Alice')
  await alice.getByRole('button', { name: 'Continue' }).click()
  await expect(alice.getByText('Invite your crew.')).toBeVisible()
  await alice.screenshot({ path: `${OUT}/03-invite-human.png` })
  await alice.getByRole('button', { name: 'Agent', exact: true }).click()
  await alice.screenshot({ path: `${OUT}/04-invite-agent.png` })
  await alice.getByRole('button', { name: 'Human', exact: true }).click()
  const link = await alice.locator('.copy-box input').first().inputValue()
  await bob.goto(link.replace(/^https?:\/\/[^/]+\/(\?[^#]*)?/, `/?relay=${encodeURIComponent(RELAY)}`))
  await bob.getByPlaceholder('Your name').fill('Sam')
  await bob.screenshot({ path: `${OUT}/05-join-mobile.png` })
  await bob.getByRole('button', { name: 'Ask to join' }).click()
  await expect(bob.getByText('Hang tight.')).toBeVisible()
  await bob.screenshot({ path: `${OUT}/06-lobby-mobile.png` })
  await alice.keyboard.press('Escape')
  await expect(alice.getByText('Sam wants to join')).toBeVisible({ timeout: 15000 })
  await alice.screenshot({ path: `${OUT}/07-lobby-notice.png` })
  await alice.locator('.notice').getByRole('button', { name: 'Admit' }).click()
  await expect(bob.getByText('You’re in. Bring your agents.')).toBeVisible({ timeout: 15000 })
  await bob.screenshot({ path: `${OUT}/08-admitted-mobile.png` })
  const roomId = alice.url().match(/#\/r\/([0-9a-f]+)/)![1]
  await alice.goto(`/?relay=${encodeURIComponent(RELAY)}#/agents/new/${roomId}`)
  await alice.screenshot({ path: `${OUT}/09-agent-editor.png`, fullPage: true })
  await alice.locator('.field input').first().fill('Claude')
  await alice.getByRole('button', { name: /Other \(OpenAI-compatible\)/ }).click()
  await alice.getByPlaceholder('https://my-server.example/v1').fill('http://localhost:7790/v1')
  await alice.locator('.card').getByRole('button', { name: 'Save' }).click()
  await alice.getByPlaceholder('model id').fill('mock-model')
  await alice.getByRole('button', { name: 'Create & add' }).click()
  await expect(bob.locator('.system-line').getByText(/Claude joined/)).toBeVisible({ timeout: 15000 })
  await bob.getByRole('button', { name: 'Maybe later' }).click()
  await bob.getByPlaceholder('Message').fill('Hi all! @Claude can you write a hello world in python?')
  await bob.getByRole('button', { name: 'Send' }).click()
  await expect(bob.locator('.msg.agent').getByText(/echo:/)).toBeVisible({ timeout: 60000 })
  await alice.getByPlaceholder('Message').fill('Here is code:\n```py:hello.py\nprint("hello")\n```')
  await alice.keyboard.press('Enter')
  await expect(bob.locator('.code').first()).toBeVisible({ timeout: 10000 })
  await bob.screenshot({ path: `${OUT}/10-chat-mobile.png` })
  await alice.screenshot({ path: `${OUT}/11-chat-desktop.png` })
  await bob.locator('[aria-label="People & agents"]').click()
  await bob.screenshot({ path: `${OUT}/12-people-mobile.png` })
  const agentPk = await alice.evaluate(() => Object.keys((window as any).__beamhop.client.state(location.hash.split('/')[2]).agents)[0])
  await alice.goto(`/?relay=${encodeURIComponent(RELAY)}#/r/${roomId}/agent/${agentPk}`)
  await alice.screenshot({ path: `${OUT}/13-agent-settings.png` })
  await alice.goto(`/?relay=${encodeURIComponent(RELAY)}#/r/${roomId}/leave`)
  await alice.screenshot({ path: `${OUT}/14-leave.png` })
  await bob.goto(`/?relay=${encodeURIComponent(RELAY)}#/`)
  await bob.screenshot({ path: `${OUT}/15-home-mobile.png` })
  await bob.goto(`/?relay=${encodeURIComponent(RELAY)}#/settings`)
  await bob.screenshot({ path: `${OUT}/16-settings-mobile.png` })
})
